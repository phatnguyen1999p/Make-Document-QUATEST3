            "- KQ được biểu thị < 1 CFU/đĩa → không phát hiện vi sinh vật mục tiêu trong thể tích khí nén được lấy mẫu "
            "~ Không có chỉ thị.",
            f"- KQTN của mẫu Blank (phiếu {KQTN_VS['blank']}): tổng số vi sinh vật hiếu khí, tổng số nấm men, tổng số nấm "
            "mốc < 1 CFU/đĩa → môi trường lấy mẫu đảm bảo kết quả.",
